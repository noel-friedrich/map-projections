import { writeFile } from 'node:fs/promises';
import { measureProjectionDistortion } from '../js/distortion.js';

const sampleCount = Number(process.argv[2] ?? 524288);
const types = ['mercator', 'same-height', 'classic', 'sinusoidal', 'robinson',
  'equal-earth', 'goode', 'equirectangular', 'tetrahedral', 'lambert-azimuthal'];
const scores = Object.fromEntries(types.map(type => [type, measureProjectionDistortion(type, sampleCount)]));
await writeFile(new URL('../js/distortion-data.js', import.meta.url),
  `// Generated by node scripts/precompute-distortion.mjs; do not edit manually.\n` +
  `// ${sampleCount} equal-area Fibonacci samples per completed projection.\n` +
  `export const distortionScores = ${JSON.stringify(scores, null, 2)};\n`);
console.table(scores);
